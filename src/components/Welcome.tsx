"use client";

import { invoke } from "@tauri-apps/api/core";
import { openUrl } from "@tauri-apps/plugin-opener";
import { ArrowRight, Check, ExternalLink, Loader2 } from "lucide-react";
import { useState, type ReactNode } from "react";
import { WAVESPEED_LINKS } from "@/lib/provider";

/** The two providers a new user can start with; WaveSpeed hosts fewer models. */
const PROVIDERS = {
  fal: {
    name: "fal.ai",
    kind: "main",
    signup: "https://fal.ai/login",
    billing: "https://fal.ai/dashboard/billing",
    keys: "https://fal.ai/dashboard/keys",
    keysHint: "On the keys page, click “Add key”, copy the key shown, then paste it below.",
  },
  wavespeed: {
    name: "WaveSpeed",
    kind: "wavespeed",
    signup: WAVESPEED_LINKS.signup,
    billing: WAVESPEED_LINKS.dashboard,
    keys: WAVESPEED_LINKS.keys,
    keysHint: "On the API keys page, create a developer key (a billing key can't run models), copy it, then paste it below.",
  },
} as const;

function Step({ n, title, done, children }: { n: number; title: string; done?: boolean; children: ReactNode }) {
  return (
    <li className="flex gap-3.5">
      <span
        className={`grid h-7 w-7 shrink-0 place-items-center rounded-full text-[12px] font-semibold ${done ? "bg-success-tint/20 text-success" : "bg-panel-2 text-fg"}`}
      >
        {done ? <Check size={14} /> : n}
      </span>
      <div className="min-w-0 flex-1 pt-0.5">
        <h3 className="text-[14px] font-medium">{title}</h3>
        <div className="mt-1 text-[13px] leading-relaxed text-muted">{children}</div>
      </div>
    </li>
  );
}

function LinkButton({ href, children }: { href: string; children: ReactNode }) {
  return (
    <button
      className="mt-2 inline-flex items-center gap-1.5 rounded-lg border border-line px-3 py-1.5 text-[12px] text-fg hover:border-accent"
      onClick={() => openUrl(href)}
    >
      {children} <ExternalLink size={12} />
    </button>
  );
}

/**
 * First-launch guide shown while no fal key is saved: create an account, add
 * credit, paste a key. The key is checked against fal right away and removed
 * again if fal refuses it, so a typo can't leave a broken key behind.
 */
export default function Welcome({ onDone }: { onDone: () => void }) {
  const [key, setKey] = useState("");
  const [state, setState] = useState<"idle" | "checking" | "ok" | "error">("idle");
  const [error, setError] = useState("");
  const [choice, setChoice] = useState<keyof typeof PROVIDERS>("fal");
  const p = PROVIDERS[choice];

  async function save() {
    setState("checking");
    try {
      await invoke("set_fal_key", { kind: p.kind, key });
      try {
        // WaveSpeed's balance is a cheap, read-only call that needs a valid key.
        await (p.kind === "wavespeed" ? invoke("wavespeed_balance") : invoke("test_fal_key", { kind: p.kind }));
      } catch (err) {
        await invoke("set_fal_key", { kind: p.kind, key: "" });
        throw err;
      }
      setState("ok");
    } catch (err) {
      setError(String(err));
      setState("error");
    }
  }

  return (
    <div className="flex h-full items-center justify-center overflow-y-auto bg-bg px-4 py-10">
      <div className="w-full max-w-[520px]">
        <div className="mb-2 grid h-10 w-10 place-items-center rounded-xl bg-accent text-base font-bold">S</div>
        <h1 className="text-[22px] font-semibold">Welcome to SimpleNode</h1>
        <p className="mt-1.5 text-[14px] leading-relaxed text-muted">
          Connect blocks (prompt, image, video) on a canvas to create with AI. Images and videos are generated by a pay-as-you-go
          service: you need an account and a key. Three steps, two minutes.
        </p>

        <div className="mt-5 flex gap-1 rounded-lg bg-panel p-1 text-[13px]">
          {(Object.keys(PROVIDERS) as (keyof typeof PROVIDERS)[]).map((id) => (
            <button
              key={id}
              disabled={state === "checking" || state === "ok"}
              className={`flex-1 rounded-md px-3 py-1.5 ${choice === id ? "bg-panel-2 text-fg" : "text-muted hover:text-fg"}`}
              onClick={() => {
                setChoice(id);
                setState("idle");
              }}
            >
              {PROVIDERS[id].name}
              {id === "fal" ? " (every model)" : " (most models)"}
            </button>
          ))}
        </div>
        {choice === "wavespeed" && (
          <p className="mt-2 text-[12px] leading-relaxed text-muted">
            WaveSpeed runs most image, video and sound models, and Recast with Wan 2.2 or Kling (Recast and the Compositor also need ffmpeg). The
            LLM tools, Camera angles and a few models need fal: you can add a fal key later in Settings.
          </p>
        )}

        <ol className="mt-7 space-y-6">
          <Step n={1} title={`Create your ${p.name} account`}>
            Sign up for free, with Google or GitHub for example.
            <br />
            <LinkButton href={p.signup}>Open {p.name}</LinkButton>
          </Step>
          <Step n={2} title="Add credit">
            Generations are billed per unit, from a few cents for an image to about a dollar for a video. A few dollars
            are enough to try.
            <br />
            <LinkButton href={p.billing}>Open billing</LinkButton>
          </Step>
          <Step n={3} title="Create a key and paste it here" done={state === "ok"}>
            {p.keysHint}
            <br />
            <LinkButton href={p.keys}>Open my keys</LinkButton>
            {state !== "ok" && (
              <div className="mt-3 flex gap-2">
                <input
                  type="password"
                  autoFocus
                  className="min-w-0 flex-1 rounded-lg border border-line bg-panel-2 px-3 py-2 text-[13px] text-fg outline-none focus:border-accent"
                  placeholder={`Paste your ${p.name} key here`}
                  value={key}
                  onChange={(e) => {
                    setKey(e.target.value);
                    if (state === "error") setState("idle");
                  }}
                  onKeyDown={(e) => e.key === "Enter" && key.trim() && save()}
                />
                <button
                  className="flex items-center gap-1.5 rounded-lg bg-fg px-3.5 py-2 text-[13px] font-medium text-bg disabled:opacity-40"
                  disabled={!key.trim() || state === "checking"}
                  onClick={save}
                >
                  {state === "checking" ? <Loader2 size={14} className="animate-spin" /> : null}
                  Check
                </button>
              </div>
            )}
            {state === "error" && (
              <p className="mt-2 text-[12px] text-danger">
                This key doesn&apos;t work ({error.replace(/^.*?:\s*/, "")}). Check that it was copied in full.
              </p>
            )}
            {state === "ok" && <p className="mt-2 text-[13px] text-success">Key checked and saved on this computer.</p>}
          </Step>
        </ol>

        <div className="mt-8 flex items-center justify-between">
          <button className="text-[12px] text-muted hover:text-fg" onClick={onDone}>
            {state === "ok" ? "" : "Later"}
          </button>
          <button
            className="flex items-center gap-2 rounded-lg bg-accent px-4 py-2 text-[13px] font-medium text-on-accent disabled:opacity-40"
            disabled={state !== "ok"}
            onClick={onDone}
          >
            Get started <ArrowRight size={14} />
          </button>
        </div>
        <p className="mt-6 text-[11px] text-muted">You can change the key later in Settings → API key.</p>
      </div>
    </div>
  );
}
